import { test, expect } from "@playwright/test";
import { createSite, login, pick, waitForHydration } from "./fixtures";

test("ページ目標の Enter は追加せず、作成後も一致の仕方・値・照合する部分を編集できる", async ({ page }) => {
  await login(page);
  await createSite(page, { id: "site_e2e_goal_page", name: "E2E Goal Page Edit" });
  const siteUrl = page.url();
  await page.goto(`${siteUrl}/goals`);
  await waitForHydration(page);
  const add = page.getByTestId("goal-add");
  const list = page.getByTestId("goals-list");
  const writes: unknown[] = [];
  page.on("request", (r) => {
    if (r.method() === "POST" && new URL(r.url()).pathname.endsWith("/goals")) writes.push(r.postDataJSON());
  });
  await add.locator('input[name="id"]').fill("g_page_edit");
  await add.locator('input[name="name"]').fill("Page edit");
  const value = add.getByRole("textbox", { name: "値", exact: true });
  await value.fill("/thanks/");
  await value.press("Enter");
  await expect(value).toHaveValue("/thanks/");
  await expect(list.getByRole("row").filter({ hasText: "g_page_edit" })).toHaveCount(0);
  expect(writes).toEqual([]);
  await value.press("Tab");
  const op = add.getByRole("combobox", { name: "一致の仕方" });
  await expect(op).toBeFocused();
  await op.press("Enter");
  await op.press("ArrowDown");
  await op.press("ArrowDown");
  await op.press("Enter");
  await expect(op).toContainText("と完全一致");
  await add.getByRole("button", { name: "追加", exact: true }).click();
  const row = list.getByRole("row").filter({ has: page.getByRole("cell", { name: "g_page_edit", exact: true }) });
  await expect(row).toContainText("パス が「/thanks/」と完全一致");
  expect(writes).toHaveLength(1);
  await row.getByRole("button", { name: /^編集/ }).click();
  await pick(list, "照合する部分", "ホスト");
  await list.getByRole("textbox", { name: "値", exact: true }).fill("example.test");
  await pick(list, "一致の仕方", "で終わる(サブドメインを含む)");
  const saved = page.waitForResponse((r) => r.request().method() === "PATCH" && new URL(r.url()).pathname.endsWith("/goals/g_page_edit"));
  await list.getByRole("button", { name: "保存", exact: true }).click();
  const response = await saved;
  expect(response.status()).toBe(200);
  expect(response.request().postDataJSON()).toEqual({ name: "Page edit", config: { page: { part: "host", op: "endsWith", value: "example.test" } } });
  await expect(row).toContainText("ホスト が「example.test」で終わる(サブドメインを含む)");
  await page.reload();
  await waitForHydration(page);
  await expect(row).toContainText("ホスト が「example.test」で終わる(サブドメインを含む)");
});
